    /**
     * Process {@link WorkflowSimTags#JOB_SUBMIT}: replace the current pending queue with the list in
     * the event payload and immediately trigger one ready scan.
     *
     * <p>This path has replace semantics, not append semantics; the sender must supply the
     * complete pending list and guarantee that its elements belong to this engine's workflow
     * context.
     *
     * <p><strong>Idempotent release scan:</strong> the first ready release originally relied on
     * the FIFO order of t=0 events (the Planner -> Clustering -> Engine chain precedes the
     * scheduler VM creation chain, so JOB_SUBMIT arrives before the scheduler's CLOUDLET_SUBMIT).
     * If that order is broken (JOB_SUBMIT is processed after CLOUDLET_SUBMIT), the scan triggered
     * by CLOUDLET_SUBMIT runs in vain against an empty queue, no one triggers a release
     * afterwards, and the workflow silently never executes. This method therefore calls
     * {@link #submitJobs()} proactively after replacing the queue; that method releases only Jobs
     * whose parent dependencies are satisfied and removes released Jobs from the queue, so
     * repeated calls cause no duplicate submission.
     *
     * @param ev event whose payload is a list of Jobs/Cloudlets
     */
    protected void processJobSubmit(SimEvent ev) {
        List<? extends Cloudlet> list = (List) ev.getData();
        setJobsList(list);
        // Idempotent ready scan: does not depend on the arrival order of JOB_SUBMIT and
        // CLOUDLET_SUBMIT.
        submitJobs();
    }

    /**
     * R5 dynamic arrival: register the submission time of each workflow input and the task
     * attribution mapping.
     *
     * <p>Called by {@link WorkflowPlanner} after parsing completes and before tasks are posted.
     * When {@code arrivalSeconds} is {@code null} or all 0.0, the behavior is bit-for-bit
     * identical to the historical single-instant submission.</p>
     *
     * @param arrivalSeconds submission time of each workflow input in simulated seconds, one-to-one
     *            with the input paths
     * @param taskWorkflowIndices mapping from task number to source input index
     */
    public void setWorkflowArrivals(List<Double> arrivalSeconds, Map<Integer, Integer> taskWorkflowIndices) {
        this.workflowArrivalSeconds = arrivalSeconds == null ? null : new ArrayList<>(arrivalSeconds);
        this.taskWorkflowIndices = taskWorkflowIndices == null
                ? Collections.<Integer, Integer>emptyMap()
                : new HashMap<>(taskWorkflowIndices);
    }

    /**
     * Return the submission time, in simulated seconds, of the workflow input that owns the given
     * Job.
     *
     * <p>R8 audit fix (P0-1): attribution is decided by the original task ID carried by the Job.
     * The Job ID space (0..N-1 under NONE clustering) is offset by one from the parsed task ID
     * space (1..N), so querying the task attribution table directly with the Job ID assigns every
     * Job to the workflow of the preceding task, and the unified stage-in Job (ID=N) hits exactly
     * the last task key and is gated to the latest arrival instant, which silently delays
     * early-arriving workflows. Now: a stage-in Job is explicitly treated as t=0 platform data
     * preparation (stagger gating is performed by each root Job by its own attribution);
     * compute/retry Jobs are attributed by their task copies, and a missing or cross-input
     * attribution fails fast instead of silently falling back to 0.0.</p>
     *
     * @param job Job to query
     * @return submission time; 0.0 when no arrival information is configured
     */
    private double arrivalSecondFor(Job job) {
        if (workflowArrivalSeconds == null || taskWorkflowIndices.isEmpty()) {
            return 0.0;
        }
        if (job.getClassType() == ClassType.STAGE_IN.value) {
            return 0.0;
        }
        Integer workflowIndex = workflowIndexOf(job);
        if (workflowIndex == null) {
            return 0.0;
        }
        if (workflowIndex.intValue() < 0 || workflowIndex.intValue() >= workflowArrivalSeconds.size()) {
            throw new IllegalStateException("Workflow index " + workflowIndex + " of Job " + job.getCloudletId()
                    + " is outside the configured arrival seconds");
        }
        Double arrivalSecond = workflowArrivalSeconds.get(workflowIndex.intValue());
        return arrivalSecond == null ? 0.0 : arrivalSecond.doubleValue();
    }

    /**
     * Decide the workflow input index of a Job by the original task ID it carries (R8 audit fix
     * P0-1).
     *
     * <p>The Job ID space (0..N-1 under NONE clustering) is offset by one from the parsed task ID
     * space (1..N), so querying {@code taskWorkflowIndices} directly with the Job ID attributes
     * every Job to the workflow of the preceding task, and the unified stage-in Job (ID=N) hits
     * exactly the last task key. Attribution now always goes through the task copies; a missing or
     * cross-input attribution of a compute/retry Job fails fast instead of silently falling
     * back.</p>
     *
     * @param job Job to attribute (must not be called for stage-in Jobs; callers filter first)
     * @return workflow input index; {@code null} for a non-compute Job without task copies
     */
    private Integer workflowIndexOf(Job job) {
        List<Task> tasks = job.getTaskList();
        if (tasks == null || tasks.isEmpty()) {
            if (job.getClassType() == ClassType.COMPUTE.value) {
                throw new IllegalStateException(
                        "Job " + job.getCloudletId() + " carries no task for workflow arrival attribution");
            }
            return null;
        }
        Integer workflowIndex = null;
        for (Task task : tasks) {
            Integer index = taskWorkflowIndices.get(task.getCloudletId());
            if (index == null) {
                throw new IllegalStateException("Task " + task.getCloudletId() + " of Job " + job.getCloudletId()
                        + " has no workflow arrival attribution");
            }
            if (workflowIndex == null) {
                workflowIndex = index;
            } else if (!workflowIndex.equals(index)) {
                throw new IllegalStateException("Job " + job.getCloudletId()
                        + " spans multiple workflow inputs; arrival attribution is ambiguous");
            }
        }
        return workflowIndex;
    }

    /**
     * Whether R5 dynamic arrival produces WORKFLOW_ARRIVED evidence.
     *
     * <p>Enabled only when the submission is multi-input or contains a non-zero submission
     * instant, which keeps the event trace of the historical single-workflow t=0 submission
     * bit-for-bit unchanged.</p>
     */
    private boolean arrivalEvidenceEnabled() {
        if (workflowArrivalSeconds == null) {
            return false;
        }
        if (workflowArrivalSeconds.size() > 1) {
            return true;
        }
        for (Double arrivalSecond : workflowArrivalSeconds) {
            if (arrivalSecond != null && arrivalSecond > 0.0) {
                return true;
            }
        }
        return false;
    }

    /**
     * Record one WORKFLOW_ARRIVED evidence entry for the workflow that owns a Job just past the
     * arrival gate (once per workflow).
     *
     * @param job Job just released
     */
    private void announceWorkflowArrivalFor(Job job) {
        if (!arrivalEvidenceEnabled()) {
            return;
        }
        // stage-in is platform preparation with no single workflow attribution, so it produces
        // no arrival evidence (R8 audit P0-1).
        if (job.getClassType() == ClassType.STAGE_IN.value) {
            return;
        }
        Integer workflowIndex = workflowIndexOf(job);
        if (workflowIndex == null || announcedWorkflowIndices.contains(workflowIndex)) {
            return;
        }
        announcedWorkflowIndices.add(workflowIndex);
        double arrivalSecond = workflowArrivalSeconds.get(workflowIndex);
        eventRecorder.record(
                SimulationEventType.WORKFLOW_ARRIVED,
                CloudSim.clock(),
                job,
                SimulationEventRecorder.attributes("workflowIndex", workflowIndex, "arrivalSecond", arrivalSecond));
    }

    /**
     * Queue one arrival rescan at the earliest not-yet-arrived submission instant; no duplicate is
     * queued while an earlier rescan is already pending.
     *
     * @param arrivalSecond target instant that triggers the rescan
     */
    private void scheduleArrivalRescan(double arrivalSecond) {
        if (pendingArrivalScanSecond == null || arrivalSecond < pendingArrivalScanSecond) {
            schedule(getId(), arrivalSecond - CloudSim.clock(), WorkflowSimTags.WORKFLOW_ARRIVAL_SCAN, null);
            pendingArrivalScanSecond = arrivalSecond;
        }
    }

    /**
     * COMM-1 fix: under the pre-execution transfer delay model, return the number of seconds a
     * compute Job must hold at its data-ready instant.
     *
     * <p>The semantics follow the AST formula of Topcuoglu TPDS 2002 list scheduling: the input
     * files of each parent task start transferring at that parent's finish time and transfer in
     * parallel, the Job becomes dispatchable at the instant the last transfer completes, and the
     * transfer window may overlap the busy period of the target VM; the VM is occupied only by
     * the compute MI. The bandwidth rules reuse the historical WorkflowSim v1 estimate
     * (SOURCE->VM uses the target VM bandwidth, VM->VM uses {@code min(bw)}, and a copy already
     * present on the target VM costs zero). {@link SimulationEventType#DATA_STAGE_IN_MODELED}
     * evidence is recorded when applicable; when no hold is needed, the input replicas are
     * registered on the target VM immediately (the same instant as registration after a transfer
     * completes).</p>
     *
     * @param job Job just released by the dependency gate
     * @return negative when the model does not apply (historical release path); 0 when no hold is
     *         needed; positive for the number of seconds to hold
     */
    private double preExecutionStageInHoldSeconds(Job job) {
        if (boundDatacenterId < 0) {
            return -1.0;
        }
        SimEntity entity = CloudSim.getEntity(boundDatacenterId);
        if (!(entity instanceof WorkflowDatacenter)) {
            return -1.0;
        }
        WorkflowDatacenter datacenter = (WorkflowDatacenter) entity;
        if (!datacenter.getDataMovementModel().isPreExecutionTransferDelayV1()) {
            return -1.0;
        }
        if (job.getClassType() != ClassType.COMPUTE.value) {
            return -1.0;
        }
        // Missing mappings are an execution contract violation, never a no-transfer fallback.
        if (job.getVmId() < 0) {
            throw new IllegalStateException(
                    "Pre-execution transfer requires a static VM mapping for Job " + job.getCloudletId());
        }
        // Under the new data movement model, compute Jobs always record transfer evidence (even
        // without real input files, to match the evidence coverage of the historical submission
        // path).
        double now = CloudSim.clock();
        PreExecutionTransfer transfer = aggregatePreExecutionTransfer(job, datacenter, now);
        double totalSeconds = transfer.totalSeconds;
        double requiredBytes = transfer.requiredBytes;
        int fileCount = transfer.fileCount;
        double maxArrival = transfer.maxArrival;
        double delay = maxArrival - now;

        eventRecorder.record(
                SimulationEventType.DATA_STAGE_IN_MODELED,
                now,
                job,
                SimulationEventRecorder.attributes(
                        "modeledTransferSeconds",
                        totalSeconds,
                        "requiredFileBytes",
                        requiredBytes,
                        "modeledTransferFileCount",
                        fileCount,
                        "dataMovementModel",
                        datacenter.getDataMovementModel().getKind().name(),
                        "dataArrivalDelaySeconds",
                        Math.max(delay, 0.0)));
        if (delay <= 0.0) {
            // The transfer already completed before readiness (or all data is local); register the
            // replicas immediately and the Job takes the ordinary release path.
            try {
                datacenter.registerStageInReplicasForComputeJob(job);
            } catch (Exception e) {
                throw new IllegalStateException(
                        "WorkflowEngine could not register pre-execution stage-in " + "replicas for Job "
                                + job.getCloudletId(),
                        e);
            }
            return 0.0;
        }
        // The event delay must not be smaller than the minimum inter-event time, to avoid
        // disturbing CloudSim event ordering.
        return Math.max(delay, CloudSim.getMinTimeBetweenEvents());
    }

    /**
     * Transfer aggregation stage of preExecutionStageInHoldSeconds() (parent attribution, external
     * inputs, byte accumulation, and exception wrapping, moved verbatim).
     */
    private PreExecutionTransfer aggregatePreExecutionTransfer(Job job, WorkflowDatacenter datacenter, double now) {
        List<FileItem> fileList = job.getFileList();
        PreExecutionTransfer transfer = new PreExecutionTransfer();
        transfer.maxArrival = now;
        Set<String> attributedNames = new HashSet<String>();
        try {
            // The files of each parent task start transferring at that parent's finish time; the
            // arrivals are independent, so take the latest arrival.
            for (Object parentObj : job.getParentList()) {
                Job parent = (Job) parentObj;
                Set<String> produced = new HashSet<String>();
                for (FileItem producedFile : parent.getFileList()) {
                    if (producedFile.getType() == Parameters.FileType.OUTPUT) {
                        produced.add(producedFile.getName());
                    }
                }
                List<FileItem> fromParent = new ArrayList<FileItem>();
                for (FileItem file : fileList) {
                    if (file.isRealInputFile(fileList) && produced.contains(file.getName())) {
                        fromParent.add(file);
                        attributedNames.add(file.getName());
                    }
                }
                if (fromParent.isEmpty()) {
                    continue;
                }
                double seconds = datacenter.estimateTransferSecondsForFiles(fromParent, job);
                validateTransferEstimate(sumTransferableBytes(fromParent, job, datacenter), seconds);
                transfer.totalSeconds =
                        addFiniteTransferQuantity(transfer.totalSeconds, seconds, "modeled transfer seconds");
                transfer.maxArrival = Math.max(transfer.maxArrival, parent.getFinishTime() + seconds);
            }
            // External inputs not produced by any parent task (SOURCE replicas) are available from
            // the start, so their transfer begins at the ready instant.
            List<FileItem> external = new ArrayList<FileItem>();
            for (FileItem file : fileList) {
                if (file.isRealInputFile(fileList) && !attributedNames.contains(file.getName())) {
                    external.add(file);
                }
            }
            if (!external.isEmpty()) {
                double seconds = datacenter.estimateTransferSecondsForFiles(external, job);
                validateTransferEstimate(sumTransferableBytes(external, job, datacenter), seconds);
                transfer.totalSeconds =
                        addFiniteTransferQuantity(transfer.totalSeconds, seconds, "modeled transfer seconds");
                transfer.maxArrival = Math.max(transfer.maxArrival, now + seconds);
            }
            for (FileItem file : fileList) {
                if (file.isRealInputFile(fileList)) {
                    transfer.requiredBytes =
                            addFiniteTransferQuantity(transfer.requiredBytes, file.getSize(), "required input bytes");
                    transfer.fileCount++;
                }
            }
        } catch (Exception e) {
            throw new IllegalStateException(
                    "WorkflowEngine could not estimate pre-execution stage-in for Job " + job.getCloudletId(), e);
        }
        return transfer;
    }

    /** Private moved-verbatim holder for the aggregates of preExecutionStageInHoldSeconds(). */
    private static final class PreExecutionTransfer {
        private double totalSeconds;
        private double requiredBytes;
        private int fileCount;
        private double maxArrival;
    }

    /**
     * Process {@link WorkflowSimTags#JOB_STAGE_IN_COMPLETE}: the pre-execution transfer window ends;
     * register the input replicas on the target VM and release the compute Job to its scheduler.
     *
     * <p>Replicas are registered only when the transfer completes, so estimates of other Jobs
     * during the transfer window do not misjudge these files as already local. The release batch
     * follows the workflow-engine delay configuration (zero under the controlled model).</p>
     *
     * @param ev event whose payload is a compute Job owned by this engine
     */
    protected void processPreExecutionStageInComplete(SimEvent ev) {
        Job job = (Job) ev.getData();
        WorkflowDatacenter datacenter = (WorkflowDatacenter) CloudSim.getEntity(boundDatacenterId);
        try {
            datacenter.registerStageInReplicasForComputeJob(job);
        } catch (Exception e) {
            throw new IllegalStateException(
                    "WorkflowEngine could not register pre-execution stage-in " + "replicas for Job "
                            + job.getCloudletId(),
                    e);
        }
        List<Job> batch = new ArrayList<Job>();
        batch.add(job);
        dispatchReadyBatch(job.getUserId(), batch);
    }

    /**
     * R2 link contention model: register the input transfer groups of a compute Job into the fluid
     * contention engine at the data-ready instant.
     *
     * <p>The transfer group partition matches the contention-free pre-execution model (one group
     * per parent task output plus one group for external inputs); the nominal rate of each group
     * is the aggregate rate of the historical bandwidth rules (bytes / contention-free estimated
     * seconds). Files within a group are serialized, and groups share capacity fairly at the same
     * VM endpoint. All transfer groups start at the data-ready instant (no back-dating of partial
     * progress from an earlier parent finish time), so a completion instant is never earlier than
     * the corresponding value of the contention-free model.</p>
     *
     * <p>When every input is a local replica (zero transfer), the replicas are registered and the
     * Job released immediately, consistent with the zero-hold semantics of the contention-free
     * model; otherwise a {@link WorkflowSimTags#TRANSFER_CONTENTION_CHECK} check event is
     * scheduled.</p>
     *
     * @param job compute Job just released by the dependency gate
     * @return true when the contention path has taken over this Job; false when the model does not
     *         apply (ordinary release path)
     */
    private boolean startContentionStageIn(Job job) {
        if (boundDatacenterId < 0) {
            return false;
        }
        SimEntity entity = CloudSim.getEntity(boundDatacenterId);
        if (!(entity instanceof WorkflowDatacenter)) {
            return false;
        }
        WorkflowDatacenter datacenter = (WorkflowDatacenter) entity;
        boolean fatTree = datacenter.getDataMovementModel().isFatTreeContentionV1();
        if (!datacenter.getDataMovementModel().isPreExecutionTransferDelayWithContentionV1() && !fatTree) {
            return false;
        }
        if (job.getClassType() != ClassType.COMPUTE.value) {
            return false;
        }
        if (job.getVmId() < 0) {
            throw new IllegalStateException(
                    "Contention transfer requires a static VM mapping for Job " + job.getCloudletId());
        }
        TransferContentionEngine contention = datacenter.getTransferContentionEngine();
        double now = CloudSim.clock();
        settleContentionTransfers(datacenter, contention.advance(now).getCompletedTransferIds());
        ContentionStageInAggregates aggregates =
                registerContentionStageInGroups(job, datacenter, contention, now, fatTree);
        Map<String, Object> stageInAttributes = SimulationEventRecorder.attributes(
                "modeledTransferSeconds", aggregates.modeledSeconds,
                "requiredFileBytes", aggregates.requiredBytes,
                "modeledTransferFileCount", aggregates.fileCount,
                "dataMovementModel", datacenter.getDataMovementModel().getKind().name(),
                "contentionTransferGroupCount", (double) aggregates.pending.size());
        if (fatTree) {
            stageInAttributes.put("fatTreePathLinkCount", (double) aggregates.pathLinkCount);
        }
        eventRecorder.record(SimulationEventType.DATA_STAGE_IN_MODELED, now, job, stageInAttributes);
        if (aggregates.pending.isEmpty()) {
            // No actual transfer: join the ordinary ready batch instead of sampling WED once
            // per Job merely because a contention model was selected.
            try {
                datacenter.registerStageInReplicasForComputeJob(job);
            } catch (Exception exception) {
                throw new IllegalStateException(
                        "Could not register zero-transfer inputs for Job " + job.getCloudletId(), exception);
            }
            return false;
        }
        contentionJobPendingTransfers.put(job.getCloudletId(), aggregates.pending);
        Double nextCompletion = contention.advance(now).getNextCompletionTime();
        schedule(
                getId(),
                Math.max(nextCompletion.doubleValue() - now, CloudSim.getMinTimeBetweenEvents()),
                WorkflowSimTags.TRANSFER_CONTENTION_CHECK,
                null);
        return true;
    }

    /**
     * Group registration stage of startContentionStageIn() (parent task grouping plus external
     * inputs, moved verbatim).
     */
    private ContentionStageInAggregates registerContentionStageInGroups(
            Job job, WorkflowDatacenter datacenter, TransferContentionEngine contention, double now, boolean fatTree) {
        List<FileItem> fileList = job.getFileList();
        ContentionStageInAggregates aggregates = new ContentionStageInAggregates();
        boolean localFileSystem = ReplicaCatalog.getFileSystem() == ReplicaCatalog.FileSystem.LOCAL;
        try {
            Set<String> attributedNames = new HashSet<String>();
            // Group by parent task output: under the LOCAL file system the source endpoint is the VM
            // of the parent task; under the SHARED file system files go through shared storage, so
            // the source endpoint is SOURCE (unbounded capacity).
            for (Object parentObj : job.getParentList()) {
                Job parent = (Job) parentObj;
                List<FileItem> fromParent = collectFilesProducedByParent(parent, fileList, attributedNames);
                if (fromParent.isEmpty()) {
                    continue;
                }
                registerContentionTransferFromParent(
                        job, parent, fromParent, datacenter, contention, now, fatTree, localFileSystem, aggregates);
            }
            // External inputs (SOURCE replicas) form a group of their own.
            registerExternalInputTransfers(
                    job, fileList, datacenter, contention, now, fatTree, attributedNames, aggregates);
        } catch (Exception e) {
            throw new IllegalStateException(
                    "WorkflowEngine could not register contention stage-in " + "for Job " + job.getCloudletId(), e);
        }
        return aggregates;
    }

    /**
     * Collect the input files grouped by parent task output (moved verbatim from the parent loop
     * body).
     */
    private static List<FileItem> collectFilesProducedByParent(
            Job parent, List<FileItem> fileList, Set<String> attributedNames) {
        Set<String> produced = new HashSet<String>();
        for (FileItem producedFile : parent.getFileList()) {
            if (producedFile.getType() == Parameters.FileType.OUTPUT) {
                produced.add(producedFile.getName());
            }
        }
        List<FileItem> fromParent = new ArrayList<FileItem>();
        for (FileItem file : fileList) {
            if (file.isRealInputFile(fileList) && produced.contains(file.getName())) {
                fromParent.add(file);
                attributedNames.add(file.getName());
            }
        }
        return fromParent;
    }

    /**
     * Estimate, register, and account one parent-task transfer group (moved verbatim; the
     * continue of the original loop body became a return).
     */
    private void registerContentionTransferFromParent(
            Job job,
            Job parent,
            List<FileItem> fromParent,
            WorkflowDatacenter datacenter,
            TransferContentionEngine contention,
            double now,
            boolean fatTree,
            boolean localFileSystem,
            ContentionStageInAggregates aggregates)
            throws Exception {
        double seconds = datacenter.estimateTransferSecondsForFiles(fromParent, job);
        double bytes = sumRealInputBytes(fromParent);
        aggregates.requiredBytes = addFiniteTransferQuantity(aggregates.requiredBytes, bytes, "required input bytes");
        aggregates.fileCount += fromParent.size();
        aggregates.modeledSeconds =
                addFiniteTransferQuantity(aggregates.modeledSeconds, seconds, "modeled transfer seconds");
        // R8 audit fix (F2): a contention flow carries only the bytes that really need transfer
        // (the same basis as seconds) -- files already local contribute zero seconds and are no
        // longer counted in the contention byte volume.
        double transferredBytes = sumTransferableBytes(fromParent, job, datacenter);
        validateTransferEstimate(transferredBytes, seconds);
        if (seconds <= 0.0 || transferredBytes <= 0.0) {
            return; // The replica is already on the target VM: zero transfer.
        }
        String sourceEndpoint = localFileSystem ? "VM:" + parent.getVmId() : Parameters.SOURCE;
        long transferId = nextContentionTransferId++;
        String destinationEndpoint = "VM:" + job.getVmId();
        List<String> resources;
        if (fatTree) {
            // Fat-tree: the resource set is both endpoints plus every link key of the
            // deterministic route.
            List<String> pathLinks = Parameters.SOURCE.equals(sourceEndpoint)
                    ? java.util.Collections.<String>emptyList()
                    : datacenter.fatTreePathResources(parent.getVmId(), job.getVmId(), job.getUserId());
            aggregates.pathLinkCount += pathLinks.size();
            resources = new ArrayList<String>();
            resources.add(sourceEndpoint);
            resources.add(destinationEndpoint);
            resources.addAll(pathLinks);
            settleContentionTransfers(
                    datacenter,
                    contention
                            .addTransfer(transferId, transferredBytes, resources, transferredBytes / seconds, now)
                            .getCompletedTransferIds());
        } else {
            resources = java.util.Arrays.asList(sourceEndpoint, destinationEndpoint);
            settleContentionTransfers(
                    datacenter,
                    contention
                            .addTransfer(transferId, transferredBytes, resources, transferredBytes / seconds, now)
                            .getCompletedTransferIds());
        }
        datacenter.recordNetworkFlowBinding(
                transferId,
                job,
                Integer.valueOf(parent.getCloudletId()),
                NetworkFlowBinding.GroupKind.PARENT_GROUP_V1,
                sourceEndpoint,
                destinationEndpoint,
                resources);
        contentionTransferJobs.put(transferId, job);
        aggregates.pending.add(transferId);
    }

    /** Estimate and register the transfer group of external inputs (SOURCE replicas), moved verbatim. */
    private void registerExternalInputTransfers(
            Job job,
            List<FileItem> fileList,
            WorkflowDatacenter datacenter,
            TransferContentionEngine contention,
            double now,
            boolean fatTree,
            Set<String> attributedNames,
            ContentionStageInAggregates aggregates)
            throws Exception {
        List<FileItem> external = new ArrayList<FileItem>();
        for (FileItem file : fileList) {
            if (file.isRealInputFile(fileList) && !attributedNames.contains(file.getName())) {
                external.add(file);
            }
        }
        if (!external.isEmpty()) {
            double seconds = datacenter.estimateTransferSecondsForFiles(external, job);
            double bytes = sumRealInputBytes(external);
            aggregates.requiredBytes =
                    addFiniteTransferQuantity(aggregates.requiredBytes, bytes, "required input bytes");
            aggregates.fileCount += external.size();
            aggregates.modeledSeconds =
                    addFiniteTransferQuantity(aggregates.modeledSeconds, seconds, "modeled transfer seconds");
            // R8 audit fix (F2): same basis as the parent group, build a flow only for the bytes
            // that really transfer.
            double transferredBytes = sumTransferableBytes(external, job, datacenter);
            validateTransferEstimate(transferredBytes, seconds);
            if (seconds > 0.0 && transferredBytes > 0.0) {
                long transferId = nextContentionTransferId++;
                String destinationEndpoint = "VM:" + job.getVmId();
                List<String> resources;
                if (fatTree) {
                    // Honest boundary v1: external input traffic does not traverse the Fat-tree and
                    // occupies only the target endpoint.
                    resources = java.util.Collections.singletonList(destinationEndpoint);
                    settleContentionTransfers(
                            datacenter,
                            contention
                                    .addTransfer(
                                            transferId, transferredBytes, resources, transferredBytes / seconds, now)
                                    .getCompletedTransferIds());
                } else {
                    resources = java.util.Arrays.asList(Parameters.SOURCE, destinationEndpoint);
                    settleContentionTransfers(
                            datacenter,
                            contention
                                    .addTransfer(
                                            transferId, transferredBytes, resources, transferredBytes / seconds, now)
                                    .getCompletedTransferIds());
                }
                datacenter.recordNetworkFlowBinding(
                        transferId,
                        job,
                        null,
                        NetworkFlowBinding.GroupKind.EXTERNAL_GROUP_V1,
                        Parameters.SOURCE,
                        destinationEndpoint,
                        resources);
                contentionTransferJobs.put(transferId, job);
                aggregates.pending.add(transferId);
            }
        }
    }

    /** Private moved-verbatim holder for the group registration aggregates of startContentionStageIn(). */
    private static final class ContentionStageInAggregates {
        private final Set<Long> pending = new LinkedHashSet<Long>();
        private double requiredBytes;
        private int fileCount;
        private int pathLinkCount;
        private double modeledSeconds;
    }

    /** Accumulate the byte volume of a group of files (all of them real input files). */
    private static double sumRealInputBytes(List<FileItem> files) {
        double bytes = 0.0;
        for (FileItem file : files) {
            bytes = addFiniteTransferQuantity(bytes, file.getSize(), "required input bytes");
        }
        return bytes;
    }

    /**
     * Total bytes of a group that really need transfer (the same basis as
     * estimateTransferSecondsForFiles).
     *
     * <p>The files in the group have already been filtered to real inputs; a local hit contributes
     * zero seconds and is not counted in the bytes either, so the byte-per-second ratio of the
     * contention flow stays consistent with the per-file V1 estimate (R8 audit fix F2).</p>
     */
    private double sumTransferableBytes(List<FileItem> files, Job job, WorkflowDatacenter datacenter) {
        double bytes = 0.0;
        for (FileItem file : files) {
            boolean local = datacenter.isFileLocalForJob(file, job);
            datacenter.recordNetworkInputDemand(file, local);
            if (!local) {
                bytes = addFiniteTransferQuantity(bytes, file.getSize(), "transferable bytes");
            }
        }
        return bytes;
    }

    private static double addFiniteTransferQuantity(double total, double value, String field) {
        double result = total + value;
        if (!Double.isFinite(total)
                || total < 0.0
                || !Double.isFinite(value)
                || value < 0.0
                || !Double.isFinite(result)) {
            throw new IllegalArgumentException("Non-finite or negative " + field + " aggregate");
        }
        return result;
    }

    /** A positive nonlocal demand cannot silently become the zero-transfer path by underflow. */
    private static void validateTransferEstimate(double transferredBytes, double seconds) {
        if (!Double.isFinite(seconds) || seconds < 0.0) {
            throw new IllegalArgumentException("Transfer estimate must be finite and nonnegative");
        }
        if (transferredBytes > 0.0) {
            double rate = transferredBytes / seconds;
            if (!(seconds > 0.0) || !(rate > 0.0) || !Double.isFinite(rate)) {
                throw new IllegalArgumentException(
                        "Positive nonlocal bytes require representable positive transfer seconds and rate");
            }
        }
    }

    /**
     * Process {@link WorkflowSimTags#TRANSFER_CONTENTION_CHECK}: advance the fluid contention
     * engine integration to the current clock and settle the completed transfer groups; when all
     * transfer groups of a compute Job are done, register its input replicas and release it to the
     * scheduler; while transfers are still active, reschedule the next check.
     *
     * @param ev check event without payload
     */
    protected void processTransferContentionCheck(SimEvent ev) {
        WorkflowDatacenter datacenter = (WorkflowDatacenter) CloudSim.getEntity(boundDatacenterId);
        TransferContentionEngine contention = datacenter.getTransferContentionEngine();
        double now = CloudSim.clock();
        TransferContentionEngine.AdvanceResult result = contention.advance(now);
        settleContentionTransfers(datacenter, result.getCompletedTransferIds());
        Double nextCompletion = result.getNextCompletionTime();
        if (nextCompletion != null) {
            schedule(
                    getId(),
                    Math.max(nextCompletion.doubleValue() - now, CloudSim.getMinTimeBetweenEvents()),
                    WorkflowSimTags.TRANSFER_CONTENTION_CHECK,
                    null);
        }
    }

    /**
     * Both addTransfer and the timed check can complete an old flow, so the pending transfer set
     * of each Job must be reclaimed in one place.
     */
    private void settleContentionTransfers(WorkflowDatacenter datacenter, List<Long> completed) {
        List<Job> readyJobs = new ArrayList<Job>();
        for (Long transferId : completed) {
            Job job = contentionTransferJobs.remove(transferId);
            if (job == null) {
                continue;
            }
            Set<Long> pending = contentionJobPendingTransfers.get(job.getCloudletId());
            if (pending == null) {
                throw new IllegalStateException("Completed transfer has no pending Job " + job.getCloudletId());
            }
            pending.remove(transferId);
            if (pending.isEmpty()) {
                contentionJobPendingTransfers.remove(job.getCloudletId());
                readyJobs.add(job);
            }
        }
        for (Job job : readyJobs) {
            dispatchContentionStageInComplete(datacenter, job);
        }
    }

    /**
     * Register the input replicas after all contention transfers complete and release the compute
     * Job to its scheduler.
     */
    private void dispatchContentionStageInComplete(WorkflowDatacenter datacenter, Job job) {
        try {
            datacenter.registerStageInReplicasForComputeJob(job);
        } catch (Exception e) {
            throw new IllegalStateException(
                    "WorkflowEngine could not register contention stage-in " + "replicas for Job "
                            + job.getCloudletId(),
                    e);
        }
        List<Job> batch = new ArrayList<Job>();
        batch.add(job);
        dispatchReadyBatch(job.getUserId(), batch);
    }

    /**
     * Process a Job returned by a scheduler and advance failure recovery or workflow termination.
     *
     * <p>A failed Job is handed to {@link ReclusteringEngine} to produce one or more retry Jobs;
     * every new Job records {@link SimulationEventType#RETRY_JOB_CREATED}. Regardless of success
     * or failure, the current attempt enters the received list and the in-flight submission count
     * is decremented. The end-of-simulation event is sent to all schedulers only when the pending
     * queue is empty and the in-flight count is zero; otherwise one more ready scan is triggered.
     *
     * @param ev event whose payload is the returned Job
     * @pre ev != $null
     * @post $none
     */
    protected void processJobReturn(SimEvent ev) {

        Job job = (Job) ev.getData();
        if (job.getCloudletStatus() == Cloudlet.FAILED) {
            // Input or historical Job IDs may be non-contiguous, but a retry ID must still be
            // unique across the three queues.
            int newId = nextAvailableJobId(job);
            List<Job> retries = ReclusteringEngine.process(job, newId);
            if (retries.isEmpty()) {
                throw new IllegalStateException("Failed job " + job.getCloudletId() + " produced no retry jobs");
            }
            enforceRetryBudget(job, retries.size());
            getJobsList().addAll(retries);
            retryJobsCreated += retries.size();
            for (Job retry : retries) {
                // PLAT-13: record the association between the retry Job and the original failed
                // Job so the JOB_READY event can carry the extra attribute.
                retryOfFailedJobIds.put(retry.getCloudletId(), job.getCloudletId());
                eventRecorder.record(
                        SimulationEventType.RETRY_JOB_CREATED,
                        CloudSim.clock(),
                        retry,
                        SimulationEventRecorder.attributes("failedJobId", job.getCloudletId()));
            }
        }

        getJobsReceivedList().add(job);
        if (job.getCloudletStatus() == Cloudlet.SUCCESS) {
            receivedSuccessfulJobIds.add(job.getCloudletId());
        }
        jobsSubmitted--;
        if (getJobsList().isEmpty() && jobsSubmitted == 0) {
            if (coherentDataflow != null) {
                scheduleCoherentCheck();
                finishCoherentIfIdle();
                return;
            }
            // With no pending or in-flight Job left, tell every scheduler to end this simulation.
            for (int i = 0; i < getSchedulerIds().size(); i++) {
                sendNow(getSchedulerId(i), CloudSimTags.END_OF_SIMULATION, null);
            }
        } else {
            sendNow(this.getId(), CloudSimTags.CLOUDLET_SUBMIT, null);
        }
    }

    /**
     * Allocate a retry Job an identifier strictly greater than the maximum ID in the three workflow
     * queues.
     *
     * @param currentJob Job just returned and possibly failed
     * @return the next Job ID that can be used safely
     * @throws IllegalStateException when the maximum ID is already {@link Integer#MAX_VALUE}
     */
    private int nextAvailableJobId(Job currentJob) {
        int maximum = currentJob.getCloudletId();
        maximum = Math.max(maximum, maximumJobId(getJobsList()));
        maximum = Math.max(maximum, maximumJobId(getJobsSubmittedList()));
        maximum = Math.max(maximum, maximumJobId(getJobsReceivedList()));
        if (maximum == Integer.MAX_VALUE) {
            throw new IllegalStateException("Cannot allocate a retry Job ID after Integer.MAX_VALUE");
        }
        return maximum + 1;
    }

    /**
     * Check the total retry Job limit declared by the modern failure configuration before
     * submitting any retry.
     */
    private void enforceRetryBudget(Job failedJob, int requestedRetryJobs) {
        int budget = FailureParameters.getMaxTotalRetryJobs();
        if (budget < 0) {
            return;
        }
        if (requestedRetryJobs <= 0 || retryJobsCreated > budget - requestedRetryJobs) {
            throw new RetryLimitExceededException(
                    failedJob.getCloudletId(),
                    retryJobsCreated,
                    requestedRetryJobs,
                    budget,
                    FailureParameters.getRootSeed());
        }
    }

    /**
     * Return the maximum Job ID in a list and reject a Cloudlet that is not a Job, so retry
     * numbering never diverges from workflow semantics.
     */
    private static int maximumJobId(List<? extends Cloudlet> jobs) {
        int maximum = -1;
        for (Cloudlet cloudlet : jobs) {
            if (!(cloudlet instanceof Job)) {
                throw new IllegalStateException("Workflow Engine contains a non-Job cloudlet");
            }
            maximum = Math.max(maximum, cloudlet.getCloudletId());
        }
        return maximum;
    }

