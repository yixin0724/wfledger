    /**
     * Append Jobs to the queue waiting for the dependency gate.
     *
     * <p>This method only appends to the list and sends no submission event; the actual release
     * is performed by {@link #submitJobs()} inside the engine lifecycle.
     *
     * @param list list of Jobs/Cloudlets to process
     */
    public void submitCloudletList(List<? extends Cloudlet> list) {
        getJobsList().addAll(list);
    }

    /**
     * Dispatch the events received by the workflow engine.
     *
     * <p>The resource characteristics request is broadcast to the schedulers;
     * {@code CLOUDLET_SUBMIT} triggers a ready Job scan; {@code CLOUDLET_RETURN} drives retry or
     * successor release; {@code JOB_SUBMIT} replaces the pending list with the event payload; the
     * end-of-simulation event shuts down this entity. Unknown tags only write diagnostics.
     *
     * @param ev CloudSim event
     */
    @Override
    public void processEvent(SimEvent ev) {
        switch (ev.getTag()) {
                // Forward the resource characteristics request to every runtime scheduler at startup.
            case CloudSimTags.RESOURCE_CHARACTERISTICS_REQUEST:
                processResourceCharacteristicsRequest(ev);
                break;
                // A scheduler notifies the engine to start releasing the currently ready Jobs once
                // its VMs are created.
            case CloudSimTags.CLOUDLET_SUBMIT:
                submitJobs();
                break;
            case CloudSimTags.CLOUDLET_RETURN:
                processJobReturn(ev);
                break;
            case CloudSimTags.END_OF_SIMULATION:
                shutdownEntity();
                break;
            case WorkflowSimTags.JOB_SUBMIT:
                processJobSubmit(ev);
                break;
            case WorkflowSimTags.JOB_STAGE_IN_COMPLETE:
                // COMM-1 fix: under the pre-execution transfer delay model the transfer window ends
                // and the compute Job is released to the scheduler.
                processPreExecutionStageInComplete(ev);
                break;
            case WorkflowSimTags.TRANSFER_CONTENTION_CHECK:
                // R2 link contention model: integrate and advance every active transfer at the
                // current clock, then settle the completed transfer groups.
                processTransferContentionCheck(ev);
                break;
            case WorkflowSimTags.COHERENT_DATAFLOW_CHECK:
                processCoherentDataflowCheck(ev);
                break;
            case WorkflowSimTags.WORKFLOW_ARRIVAL_SCAN:
                // R5 dynamic arrival: idempotent ready rescan triggered at the earliest
                // not-yet-arrived instant.
                pendingArrivalScanSecond = null;
                submitJobs();
                break;
            default:
                processOtherEvent(ev);
                break;
        }
    }

    /**
     * Broadcast the resource characteristics request to all runtime schedulers.
     *
     * @param ev CloudSim event that triggered the broadcast; the event payload is not processed
     */
    protected void processResourceCharacteristicsRequest(SimEvent ev) {
        for (int i = 0; i < getSchedulerIds().size(); i++) {
            schedule(getSchedulerId(i), 0, CloudSimTags.RESOURCE_CHARACTERISTICS_REQUEST);
        }
    }

