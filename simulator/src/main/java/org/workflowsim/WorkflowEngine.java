    /**
     * Create a workflow engine with one runtime scheduler.
     *
     * @param name SimEntity name, which must satisfy the CloudSim entity naming requirements
     * @throws Exception when parent entity initialization fails
     * @pre name != null
     * @post $none
     */
    public WorkflowEngine(String name) throws Exception {
        this(name, 1);
    }

    /**
     * Create the given number of runtime schedulers and establish their back reference to this
     * engine.
     *
     * <p>{@code schedulers} is a count, not a scheduler entity ID. Normal operation requires it
     * to be positive; this constructor keeps the historical behavior and does not additionally
     * reject zero or negative values, and later use of the default-scheduler API may then fail
     * because index 0 does not exist.
     *
     * @param name SimEntity name
     * @param schedulers number of schedulers to create
     * @throws Exception when parent entity or child scheduler initialization fails
     */
    public WorkflowEngine(String name, int schedulers) throws Exception {
        super(name);

        setJobsList(new ArrayList<>());
        setJobsSubmittedList(new ArrayList<>());
        setJobsReceivedList(new ArrayList<>());

        jobsSubmitted = 0;
        retryJobsCreated = 0;

        setSchedulers(new ArrayList<>());
        setSchedulerIds(new ArrayList<>());

        for (int i = 0; i < schedulers; i++) {
            WorkflowScheduler wfs = new WorkflowScheduler(name + "_Scheduler_" + i);
            getSchedulers().add(wfs);
            getSchedulerIds().add(wfs.getId());
            wfs.setWorkflowEngineId(this.getId());
        }
    }

    /**
     * Hand the list of VMs to create to the given runtime scheduler.
     *
     * @param list list of VMs to create
     * @param schedulerId scheduler <strong>index</strong>, not a CloudSim scheduler entity ID
     */
    public void submitVmList(List<? extends Vm> list, int schedulerId) {
        getScheduler(schedulerId).submitVmList(list);
    }

    /**
     * Hand the VM list to the default scheduler (index 0) and keep it so that
     * {@link #getAllVmList()} can return it directly.
     *
     * <p>This is the compatibility entry point of the single-scheduler era. Multi-scheduler
     * callers should use the overload that takes a scheduler index; otherwise this field can
     * only reflect the VM list of the default scheduler.
     *
     * @param list list of VMs to create
     */
    public void submitVmList(List<? extends Vm> list) {
        // Compatibility entry point of the single-scheduler era; multi-scheduler callers must
        // name the target index explicitly.
        getScheduler(0).submitVmList(list);
        setVmList(list);
    }

    /**
     * Return the VM list visible to the engine.
     *
     * <p>If the default-scheduler entry point saved a non-empty VM list, that list is returned
     * directly; otherwise the VM lists of all schedulers are aggregated in scheduler order. The
     * result is a mutable list view or aggregate of the historical API, and callers must not use
     * it to modify scheduler state.
     *
     * @return the default VM list, or the VM lists aggregated in scheduler order
     */
    public List<? extends Vm> getAllVmList() {
        if (this.vmList != null && !this.vmList.isEmpty()) {
            return this.vmList;
        } else {
            List list = new ArrayList();
            for (int i = 0; i < getSchedulers().size(); i++) {
                list.addAll(getScheduler(i).getVmList());
            }
            return list;
        }
    }

