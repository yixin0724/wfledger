    /**
     * Remove Jobs whose parent dependencies have returned from the pending queue and hand them to
     * their schedulers in batches.
     *
     * <p>Whether a Job can be released is decided by whether all of its parent Job IDs already
     * appear in {@code jobsReceivedList}; reconnecting dependencies on failure retry is the
     * responsibility of the Job graph generated by {@link ReclusteringEngine}. This method looks
     * up the submission queue with {@link Job#getUserId()} as the scheduler <strong>entity
     * ID</strong>, so callers must set that field to a value in {@link #getSchedulerIds()} rather
     * than a scheduler index.
     *
     * <p>The in-flight count is incremented and {@link SimulationEventType#JOB_READY} is recorded
     * before submission. When a workflow-engine delay is configured, the submission queue is split
     * into blocks by the interval and the delay is accumulated per block; when unconfigured, the
     * whole batch is sent immediately.
     *
     * @pre $none
     * @post $none
     */
    protected void submitJobs() {

        List<Job> list = getJobsList();
        Map<Integer, List> allocationList = new HashMap<>();
        for (int i = 0; i < getSchedulers().size(); i++) {
            List<Job> submittedList = new ArrayList<>();
            allocationList.put(getSchedulerId(i), submittedList);
        }
        int num = list.size();
        for (int i = 0; i < num; i++) {
            // After removing the current element, step the index back so that the candidate Job
            // immediately following is not skipped.
            Job job = list.get(i);
            // The Cloudlet finished flag cannot represent this engine's dependency release state.
            // PLAT-18: the dependency gate uses the O(1) successful-parent mirror index instead of a
            // linear scan; a failed attempt never releases its children.
            if (!receivedSuccessfulJobIds.contains(job.getCloudletId())) {
                List<Job> parentList = job.getParentList();
                boolean flag = true;
                for (Job parent : parentList) {
                    if (!receivedSuccessfulJobIds.contains(parent.getCloudletId())) {
                        flag = false;
                        break;
                    }
                }
                /** All parent Job IDs appear in the received list, so this Job may be queued. */
                if (flag) {
                    // R5 dynamic arrival: a Job whose submission instant has not arrived stays in the
                    // ready list; the arrival rescan event triggers another idempotent ready scan
                    // at the earliest not-yet-arrived instant.
                    double arrivalSecond = arrivalSecondFor(job);
                    if (arrivalSecond > CloudSim.clock()) {
                        scheduleArrivalRescan(arrivalSecond);
                        continue;
                    }
                    announceWorkflowArrivalFor(job);
                    org.workflowsim.data.v2.CoherentDataflowRuntime.Preparation coherentPreparation =
                            prepareCoherentInput(job);
                    // PLAT-13: the JOB_READY of a retry Job carries the association with the
                    // original failed Job, so downstream event consumers can recognize the retry
                    // attempt directly (attempt semantics).
                    recordJobReady(job, retryOfFailedJobIds.get(job.getCloudletId()), parentList.size());
                    jobsSubmitted++;
                    getJobsSubmittedList().add(job);
                    list.remove(job);
                    i--;
                    num--;
                    // COMM-1 fix: pre-execution transfer delay model
                    // (PRE_EXECUTION_TRANSFER_DELAY_V1, paper semantics). The inputs of a compute
                    // Job start transferring at the data-ready instant, the transfer window may
                    // overlap the busy period of the target VM, and the Job is released into the
                    // dispatch queue only after the transfer completes; the VM is occupied only by
                    // the compute MI. A negative value means the model does not apply (ordinary
                    // release path, behavior identical to the historical one).
                    // R2: the link contention model takes precedence -- transfer groups are
                    // registered into the contention engine and released by the contention check
                    // event once all groups complete; a true return means the contention path has
                    // taken over this Job.
                    if (coherentPreparation != null) {
                        recordDataStageInModeled(job, coherentPreparation);
                    } else if (!startContentionStageIn(job)) {
                        double stageInHoldSeconds = preExecutionStageInHoldSeconds(job);
                        if (stageInHoldSeconds < 0.0 || stageInHoldSeconds == 0.0) {
                            allocationList.get(job.getUserId()).add(job);
                        } else {
                            schedule(getId(), stageInHoldSeconds, WorkflowSimTags.JOB_STAGE_IN_COMPLETE, job);
                        }
                    }
                }
            }
        }
        appendCoherentReady(allocationList);
        scheduleCoherentCheck();
        for (int i = 0; i < getSchedulers().size(); i++) {
            dispatchReadyBatch(getSchedulerId(i), allocationList.get(getSchedulerId(i)));
        }
    }
    /** JOB_READY event recording stage of submitJobs() (PLAT-13 retry association, moved verbatim). */
    private void recordJobReady(Job job, Integer retryOfFailedJobId, int parentCount) {
        eventRecorder.record(
                SimulationEventType.JOB_READY,
                CloudSim.clock(),
                job,
                retryOfFailedJobId != null
                        ? SimulationEventRecorder.attributes(
                                "parentJobCount", parentCount, "retryOfFailedJobId", retryOfFailedJobId)
                        : SimulationEventRecorder.attributes("parentJobCount", parentCount));
    }

    /** DATA_STAGE_IN_MODELED recording stage of submitJobs() (V2 coherent data preparation, moved verbatim). */
    private void recordDataStageInModeled(
            Job job, org.workflowsim.data.v2.CoherentDataflowRuntime.Preparation coherentPreparation) {
        coherentPendingJobs.put(job.getCloudletId(), job);
        if (!coherentDataflow.isStorageVersion()) {
            eventRecorder.record(
                    SimulationEventType.DATA_STAGE_IN_MODELED,
                    CloudSim.clock(),
                    job,
                    SimulationEventRecorder.attributes(
                            "modeledTransferSeconds",
                            coherentPreparation.getIsolatedSeconds(),
                            "requiredFileBytes",
                            coherentPreparation.getRequiredBytes(),
                            "modeledTransferFileCount",
                            coherentPreparation.getReferenceCount(),
                            "dataMovementModel",
                            ((WorkflowDatacenter) CloudSim.getEntity(boundDatacenterId))
                                    .getDataMovementModel()
                                    .getKind()
                                    .name(),
                            "newFileCopies",
                            coherentPreparation.getNewCopies(),
                            "joinedFileCopies",
                            coherentPreparation.getJoinedCopies(),
                            "transferUnit",
                            "LOGICAL_FILE_V2"));
        }
    }

    /**
     * One WED rule for ordinary and post-transfer release: interval zero means an unsplit
     * batch, not discarded overhead. Positive intervals set the maximum batch size.
     * Sample once from the first Job's depth and apply it cumulatively to every sub-batch,
     * including a final partial batch. Empty batches consume no randomness.
     */
    private void dispatchReadyBatch(int scheduler, List<Job> jobs) {
        if (jobs.isEmpty()) {
            return;
        }
        int interval = Parameters.getOverheadParams().getWEDInterval();
        int batchSize = interval > 0 ? Math.min(interval, jobs.size()) : jobs.size();
        double baseDelay = Parameters.getOverheadParams().getWEDDelay(jobs);
        if (!Double.isFinite(baseDelay) || baseDelay < 0.0) {
            throw new IllegalStateException("Workflow-engine delay must be finite and non-negative");
        }
        double delay = 0.0;
        for (int first = 0; first < jobs.size(); ) {
            int end = first + Math.min(batchSize, jobs.size() - first);
            delay += baseDelay;
            if (!Double.isFinite(delay)) {
                throw new IllegalStateException("Workflow-engine batch delay overflow");
            }
            schedule(scheduler, delay, CloudSimTags.CLOUDLET_SUBMIT, new ArrayList<Job>(jobs.subList(first, end)));
            first = end;
        }
    }

