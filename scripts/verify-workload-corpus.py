#!/usr/bin/env python3
"""Verify the WfGen standard-workloads corpus and (re)build its integrity index.

Usage (from the repository root)::

    # verify the committed corpus against its index (default mode)
    python3 -B scripts/verify-workload-corpus.py datasets/wfgen-standard

    # build INDEX.json from a complete generation (every instance present)
    python3 -B scripts/verify-workload-corpus.py /tmp/wfgen-standard --write-index

The corpus is produced by ``experiments/studies/standard-workloads/generate_corpus.py``
(R7-WORKLOAD, 2026-11-25). This verifier is pure standard library and never imports
WfCommons. For every instance file present on disk it checks:

* the SHA-256 recorded in the index;
* WfFormat shape: unique task IDs, every specification task has exactly one execution
  record, parent/child symmetry, resolvable endpoints, and acyclicity (Kahn);
* every ``inputFiles``/``outputFiles`` reference resolves to a declared file, every
  declared file is referenced, and declared IDs are unique;
* runtimes are finite and strictly positive (zero or negative runtimes are rejected and
  reported), file sizes are finite and non-negative (zero-size files are counted, not
  rejected, because some recipes declare empty files);
* the canonical file-ID contract: each ID is
  ``<task_id>.<in|out><ordinal>[.<extension>]`` (ordinal zero-padded to at
  least three digits) where ``<task_id>`` is the first task
  in ascending task-ID order that references the file (``inputFiles`` before
  ``outputFiles``) and the ordinal is the file's position in that list;
* the structural statistics, which are recomputed and compared with the index; when the
  document embeds WfCommons ``specification.metrics`` the task, file, level, width, and
  byte totals must agree with the independent recomputation (conservation check).

Statistics definitions: ``tasks``; ``edges`` (parent/child pairs); ``depth`` (number of
levels, sources at level 1, a task one level below its deepest parent -- the
``WorkflowDagValidator`` convention); ``max_level_width`` (largest number of tasks on
one level); ``total_runtime_s`` (sum of ``runtimeInSeconds`` in ascending task-ID order,
rounded to 6 decimals); ``total_input_bytes`` (sum of the sizes of every
``inputFiles`` reference over all tasks, i.e. reference-weighted read volume);
``files``; ``zero_size_files``; ``total_file_bytes`` (sum of distinct declared sizes).

Entries flagged ``retained_in_standard_checkout: false`` may be absent; an absent entry
without that flag is an issue. Exit status: 0 clean, 1 issues, 2 unusable input.
"""

import argparse
import hashlib
import json
import math
import re
import sys
from pathlib import Path

INDEX_NAME = "INDEX.json"
MANIFEST_NAME = "GENERATION.json"
KINDS = (("inputFiles", "in"), ("outputFiles", "out"))
CANONICAL_SUFFIX = re.compile(r"^(?:\.[^/\s]+)?$")
STAT_KEYS = ("tasks", "edges", "depth", "max_level_width", "total_runtime_s",
             "total_input_bytes", "files", "zero_size_files", "total_file_bytes")
INDEX_BOUNDARY = (
    "WfGen synthetic instances generated by WfCommons 1.6 recipes: structures, runtimes, and"
    " file sizes are sampled from distributions learned from historical executions; they are"
    " not traces of a production execution and must not be mixed with real-execution-derived"
    " (WfInstances) or classic DAX inputs into one workload population.")


class CorpusIssue(Exception):
    """A per-instance verification failure."""


def sha256_file(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _finite(value, what):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise CorpusIssue(what + " is not a finite number")
    return value


def levels_of(tasks_by_id):
    """Return {task_id: level} with sources at level 1; raise on a cycle."""
    indegree = {task_id: len(task["parents"]) for task_id, task in tasks_by_id.items()}
    level = {task_id: 1 for task_id in tasks_by_id}
    frontier = sorted(task_id for task_id, degree in indegree.items() if degree == 0)
    visited = 0
    while frontier:
        next_frontier = []
        for task_id in frontier:
            visited += 1
            for child in tasks_by_id[task_id]["children"]:
                level[child] = max(level[child], level[task_id] + 1)
                indegree[child] -= 1
                if indegree[child] == 0:
                    next_frontier.append(child)
        frontier = sorted(next_frontier)
    if visited != len(tasks_by_id):
        raise CorpusIssue("the task graph contains a cycle ({} of {} tasks are on or behind"
                          " a cycle)".format(len(tasks_by_id) - visited, len(tasks_by_id)))
    return level


def analyze(document):
    """Validate one WfFormat document and return its structural statistics."""
    try:
        specification = document["workflow"]["specification"]
        execution = document["workflow"]["execution"]
        tasks = specification["tasks"]
        files = specification.get("files", [])
        execution_tasks = execution["tasks"]
    except (KeyError, TypeError):
        raise CorpusIssue("missing workflow.specification/execution structure")
    if not tasks:
        raise CorpusIssue("the specification has no tasks")
    tasks_by_id = {}
    for task in tasks:
        task_id = task.get("id")
        if not isinstance(task_id, str) or not task_id:
            raise CorpusIssue("a specification task has no id")
        if task_id in tasks_by_id:
            raise CorpusIssue("duplicate task id " + task_id)
        for key in ("parents", "children"):
            if not isinstance(task.get(key), list):
                raise CorpusIssue("task {} has no {} list".format(task_id, key))
        tasks_by_id[task_id] = task
    edges = 0
    for task_id, task in tasks_by_id.items():
        if len(set(task["children"])) != len(task["children"]):
            raise CorpusIssue("task {} lists a child twice".format(task_id))
        for child in task["children"]:
            if child not in tasks_by_id:
                raise CorpusIssue("task {} has unknown child {}".format(task_id, child))
            if task_id not in tasks_by_id[child]["parents"]:
                raise CorpusIssue("edge {} -> {} is missing from the child's parents"
                                  .format(task_id, child))
            edges += 1
        for parent in task["parents"]:
            if parent not in tasks_by_id:
                raise CorpusIssue("task {} has unknown parent {}".format(task_id, parent))
            if task_id not in tasks_by_id[parent]["children"]:
                raise CorpusIssue("edge {} -> {} is missing from the parent's children"
                                  .format(parent, task_id))
    level = levels_of(tasks_by_id)
    widths = {}
    for value in level.values():
        widths[value] = widths.get(value, 0) + 1

    sizes = {}
    for entry in files:
        file_id = entry.get("id")
        if not isinstance(file_id, str) or not file_id:
            raise CorpusIssue("a declared file has no id")
        if file_id in sizes:
            raise CorpusIssue("duplicate file id " + file_id)
        size = _finite(entry.get("sizeInBytes"), "size of file " + file_id)
        if size < 0:
            raise CorpusIssue("file {} has negative size {}".format(file_id, size))
        sizes[file_id] = size
    first_reference = {}
    total_input_bytes = 0
    for task_id in sorted(tasks_by_id):
        task = tasks_by_id[task_id]
        for field, kind in KINDS:
            references = task.get(field, [])
            if not isinstance(references, list):
                raise CorpusIssue("task {} {} is not a list".format(task_id, field))
            for ordinal, file_id in enumerate(references):
                if file_id not in sizes:
                    raise CorpusIssue("task {} references undeclared file {}"
                                      .format(task_id, file_id))
                first_reference.setdefault(file_id, (task_id, kind, ordinal))
                if field == "inputFiles":
                    total_input_bytes += sizes[file_id]
    unreferenced = sorted(set(sizes) - set(first_reference))
    if unreferenced:
        raise CorpusIssue("{} declared files are referenced by no task, e.g. {}"
                          .format(len(unreferenced), unreferenced[0]))
    for file_id, (task_id, kind, ordinal) in sorted(first_reference.items()):
        expected_prefix = "{}.{}{:03d}".format(task_id, kind, ordinal)
        if (not file_id.startswith(expected_prefix)
                or CANONICAL_SUFFIX.match(file_id[len(expected_prefix):]) is None):
            raise CorpusIssue("file id {} violates the canonical rule (expected prefix {})"
                              .format(file_id, expected_prefix))

    runtimes = {}
    for entry in execution_tasks:
        task_id = entry.get("id")
        if task_id not in tasks_by_id:
            raise CorpusIssue("execution record for unknown task {}".format(task_id))
        if task_id in runtimes:
            raise CorpusIssue("duplicate execution record for task " + task_id)
        runtimes[task_id] = _finite(entry.get("runtimeInSeconds"), "runtime of " + str(task_id))
    missing = sorted(set(tasks_by_id) - set(runtimes))
    if missing:
        raise CorpusIssue("{} tasks have no execution record, e.g. {}".format(len(missing),
                                                                             missing[0]))
    non_positive = sorted(task_id for task_id, value in runtimes.items() if value <= 0)
    if non_positive:
        raise CorpusIssue("{} tasks have zero or negative runtime, e.g. {} = {}".format(
            len(non_positive), non_positive[0], runtimes[non_positive[0]]))
    total_runtime = 0.0
    for task_id in sorted(runtimes):
        total_runtime += runtimes[task_id]

    stats = {
        "tasks": len(tasks_by_id),
        "edges": edges,
        "depth": max(widths),
        "max_level_width": max(widths.values()),
        "total_runtime_s": round(total_runtime, 6),
        "total_input_bytes": total_input_bytes,
        "files": len(sizes),
        "zero_size_files": sum(1 for value in sizes.values() if value == 0),
        "total_file_bytes": sum(sizes[file_id] for file_id in sorted(sizes)),
    }
    embedded = specification.get("metrics")
    if isinstance(embedded, dict):
        for source, target in (("numberOfTasks", "tasks"), ("numberOfFiles", "files"),
                               ("numberOfLevels", "depth"), ("maximumWidth", "max_level_width"),
                               ("sumOfFileSizesInBytes", "total_file_bytes")):
            if source in embedded and embedded[source] != stats[target]:
                raise CorpusIssue("embedded metrics.{} = {} disagrees with recomputed {} = {}"
                                  .format(source, embedded[source], target, stats[target]))
    return stats


def verify_corpus(corpus_dir):
    """Return (issues, counts) for a corpus directory holding INDEX.json."""
    corpus_dir = Path(corpus_dir)
    index_path = corpus_dir / INDEX_NAME
    if not index_path.is_file():
        raise ValueError("missing corpus index: " + str(index_path))
    index = json.loads(index_path.read_text(encoding="utf-8"))
    instances = index.get("instances")
    if not isinstance(instances, list):
        raise ValueError("the corpus index has no instances list")
    issues = []
    counts = {"entries": len(instances), "verified": 0, "absent_not_retained": 0,
              "zero_size_files": 0}
    if index.get("n_instances") != len(instances):
        issues.append("index n_instances {} disagrees with {} entries".format(
            index.get("n_instances"), len(instances)))
    seen = set()
    for entry in instances:
        rel = entry.get("wfformat_json")
        subject = str(rel)
        if not isinstance(rel, str) or rel in seen or ".." in Path(rel).parts:
            issues.append(subject + ": invalid or duplicate instance path")
            continue
        seen.add(rel)
        path = corpus_dir / rel
        if not path.is_file():
            if entry.get("retained_in_standard_checkout", True) is not False:
                issues.append(subject + ": missing but claimed retained in the standard checkout")
            else:
                counts["absent_not_retained"] += 1
            continue
        actual = sha256_file(path)
        if actual != entry.get("sha256"):
            issues.append("{}: sha256 mismatch (recorded {}, actual {})".format(
                subject, entry.get("sha256"), actual))
            continue
        try:
            stats = analyze(json.loads(path.read_text(encoding="utf-8")))
        except (CorpusIssue, ValueError) as error:
            issues.append(subject + ": " + str(error))
            continue
        if stats != entry.get("stats"):
            issues.append("{}: recomputed stats {} disagree with indexed stats {}".format(
                subject, stats, entry.get("stats")))
            continue
        if stats["tasks"] != entry.get("num_tasks"):
            issues.append("{}: num_tasks {} disagrees with {} tasks".format(
                subject, entry.get("num_tasks"), stats["tasks"]))
            continue
        counts["verified"] += 1
        counts["zero_size_files"] += stats["zero_size_files"]
    return issues, counts


def build_index(corpus_dir):
    """Build the index document from GENERATION.json and the complete corpus on disk."""
    corpus_dir = Path(corpus_dir)
    manifest_path = corpus_dir / MANIFEST_NAME
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = []
    for record in manifest["instances"]:
        path = corpus_dir / record["wfformat_json"]
        if not path.is_file():
            raise ValueError("--write-index needs every instance on disk; missing "
                             + record["wfformat_json"])
        stats = analyze(json.loads(path.read_text(encoding="utf-8")))
        if stats["tasks"] != record["num_tasks"]:
            raise ValueError("manifest num_tasks disagrees for " + record["wfformat_json"])
        entry = dict(record)
        entry["sha256"] = sha256_file(path)
        if entry["sha256"] != record["sha256"]:
            raise ValueError("manifest sha256 disagrees for " + record["wfformat_json"])
        entry["stats"] = stats
        entries.append(entry)
    return {
        "description": "WfGen standard-workloads corpus " + manifest["corpus"]
                       + ": WfCommons WfFormat JSON with canonical file IDs and fixed timestamps.",
        "generator": "experiments/studies/standard-workloads/generate_corpus.py",
        "spec": "experiments/studies/standard-workloads/spec.json",
        "spec_sha256": manifest["spec_sha256"],
        "environment": manifest["environment"],
        "seed_rule": manifest["seed_rule"],
        "exclusions": manifest["exclusions"],
        "boundary": INDEX_BOUNDARY,
        "verifier": "scripts/verify-workload-corpus.py",
        "n_instances": len(entries),
        "n_auxiliary_files": 1,
        "auxiliary_files": [{"file": MANIFEST_NAME, "sha256": sha256_file(manifest_path),
                             "role": "generation manifest (not a simulation-experiment manifest)"}],
        "instances": entries,
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("corpus_dir", type=Path)
    parser.add_argument("--write-index", action="store_true",
                        help="build INDEX.json from GENERATION.json and the complete corpus")
    args = parser.parse_args(argv)
    try:
        if args.write_index:
            index = build_index(args.corpus_dir)
            text = json.dumps(index, indent=2, sort_keys=False) + "\n"
            (args.corpus_dir / INDEX_NAME).write_bytes(text.encode("ascii"))
            print("wrote {} with {} instances".format(args.corpus_dir / INDEX_NAME,
                                                     index["n_instances"]))
            return 0
        issues, counts = verify_corpus(args.corpus_dir)
    except (OSError, ValueError, KeyError, CorpusIssue) as error:
        print("verify-workload-corpus: " + str(error), file=sys.stderr)
        return 2
    print("Checked {entries} indexed instances: {verified} verified,"
          " {absent_not_retained} absent and not retained;"
          " {zero_size_files} zero-size files in verified instances;"
          " {n} issues.".format(n=len(issues), **counts))
    for issue in issues:
        print(issue)
    return 1 if issues else 0


if __name__ == "__main__":
    sys.exit(main())
